const { inMethod, L } = require('../harness');

module.exports = [
  { name: 'insert local variable', before: inMethod(''), after: inMethod('int x = 1;'), expect: [L('+ var C.M()', 'int x = 1')] },
  { name: 'multi-declarator split', before: inMethod(''), after: inMethod('int a = 1, b = 2;'), expect: [L('+ var C.M()', 'int a = 1'), L('+ var C.M()', 'int b = 2')] },
  { name: 'add else branch', before: inMethod('if (true) { }'), after: inMethod('if (true) { } else { }'), expect: [L('+ else C.M()')] },
  { name: 'change condition', before: inMethod('if (a > 1) { }'), after: inMethod('if (a >= 1) { }'), expect: [L('~ if C.M()', 'op > -> >=')] },
  { name: 'insert switch case', before: inMethod('switch (x) { case 1: break; }'), after: inMethod('switch (x) { case 1: break; case 2: break; }'), expect: [L('+ case C.M()', 'case 2:'), L('+ break C.M()')] },
  { name: 'insert return', before: inMethod(''), after: inMethod('return;'), expect: [L('+ return C.M()', 'return;')] },
  { name: 'move statement within block', before: inMethod('A();\nB();'), after: inMethod('B();\nA();'), expect: [L('mv call C.M() @1/2 -> @2/2', 'A();')] },

  
  { name: 'insert if', before: inMethod(''), after: inMethod('if (true) { }'),
    expect: [L('+ if C.M()', 'if (true)')],
    forbid: [L('+ block'), L('mv block')] },
  { name: 'insert try/catch', before: inMethod(''), after: inMethod('try { } catch (Exception e) { }'),
    expect: [L('+ try C.M()'), L('+ catch C.M()')],
    forbid: [L('+ block'), L('mv block')] },
  { name: 'wrap statement in if', before: inMethod('Foo();'), after: inMethod('if (ok) { Foo(); }'),
    expect: [L('+ if C.M()', 'if (ok)')],
    forbid: [L('+ block'), L('mv block')],
    known: 'wrapped statement is reported as "mv block { Foo(); }" instead of "Foo(); moved into if (ok)"' },
  { name: 'wrap in using', before: inMethod('Foo();'), after: inMethod('using (var s = Open()) { Foo(); }'),
    expect: [L('+ using-block C.M()', 'using (var s = Open())')],
    forbid: [L('+ block'), L('mv block')],
    known: 'same as wrap in if' },
  { name: 'unwrap statement from if', before: inMethod('if (ok) { Foo(); }'), after: inMethod('Foo();'),
    expect: [L('- if C.M()', 'if (ok)')],
    forbid: [L('move'), L('- block')] },
  { name: 'unwrap keeps the statement visible', before: inMethod('if (ok) { Foo(); }'), after: inMethod('Foo();'),
    expect: [/Foo\(\);/],
    known: 'log only says "- if ...", the log does not show that Foo(); is now at method level' },
  { name: 'for → foreach', before: inMethod('for (int i = 0; i < 3; i++) { }'), after: inMethod('foreach (var i in xs) { }'),
    expect: [L('+ foreach C.M()'), L('- for C.M()')],
    forbid: [L('move')] },
  { name: 'move statement out of if block', before: inMethod('if (ok) { A(); }'), after: inMethod('A();\nif (ok) { }'),
    expect: [/A\(\);/],
    known: 'probe: same index (0), different parent; must not be dropped as a no-op move' },
];